"""As variáveis que apresentam maior amplitude são o consumo_mensal_kwh (que varia desde unidades com consumo baixo até valores elevados acima de 1500 kWh) e a demanda_maxima_kw.
Observação: Analisar apenas o consumo mensal poderia esconder diferenças cruciais de comportamento porque duas unidades podem consumir a mesma quantidade total de energia no mês (kWh), mas uma delas pode ter um pico de demanda muito alto concentrado em horários de ponta ou um perfil de consumo predominantemente noturno, enquanto a outra possui um perfil linear e constante. O agrupamento (clustering) com múltiplas variáveis evita essa distorção.
"""

# Selecione as três variáveis em X.
X = df[['consumo_mensal_kwh', 'demanda_maxima_kw', 'consumo_noturno_pct']]

# Crie um StandardScaler e obtenha X_padronizado.
scaler = StandardScaler()
