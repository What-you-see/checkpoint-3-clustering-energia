print(f"\nSilhouette Score Final (para k={k_escolhido}): {score_final:.4f}")

display(df_resultados.head())

"""Foi escolhido $k = 3$. A justificativa baseia-se na convergência dos indicadores visuais e estatísticos: o Método Elbow apontou uma clara inflexão nesse ponto (evitando a complexidade excessiva de agrupamentos maiores) e o Silhouette Score validou que 3 grupos mantêm uma boa separação e coerência interna entre as unidades consumidoras."""

