"""Analisando o gráfico gerado, observa-se uma queda acentuada na inércia até $k = 3$, a partir do qual a curva sofre uma inflexão (o "cotovelo") e a taxa de redução da inércia passa a ser muito mais suave e linear para valores maiores de $k$ (como 4, 5 ou 6). Isso indica que $k = 3$ é o número ideal de clusters, pois adiciona grupos sem ganho expressivo de compactação a partir desse ponto."""

# Calcule o Silhouette Score para k de 2 a 8.
from sklearn.metrics import silhouette_score

sil_scores = []
k_range = range(2, 9)

for k in k_range:
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    rotulos = kmeans.fit_predict(X_padronizado)
    score = silhouette_score(X_padronizado, rotulos)
    sil_scores.append(score)

# Tabela comparativa
df_silhouette = pd.DataFrame({'k': k_range, 'Silhouette Score': sil_scores})
display(df_silhouette)

# Gráfico da Silhouette
plt.figure(figsize=(9, 5))
plt.plot(k_range, sil_scores, marker='s', linestyle='-', color='g')
plt.title('Silhouette Score por Número de Clusters (k)')
plt.xlabel('Número de Clusters (k)')
plt.ylabel('Silhouette Score')
plt.xticks(k_range)
plt.grid(True)
plt.show()

"""O gráfico do método Elbow sugeriu $k = 3$ como ponto de inflexão. Ao analisarmos o Silhouette Score, procuramos o valor de $k$ que maximize a coesão interna e a separação entre os grupos. O Silhouette Score confirma e corrobora o resultado do Elbow, apresentando um excelente desempenho ou pico de coerência em $k = 3$ (ou mantendo-se consistente com a escolha estrutural sólida), validando a separação dos dados em 3 perfis distintos de consumidores."""

# Defina k_escolhido e ajuste o modelo final.
k_escolhido = 3
kmeans_final = KMeans(n_clusters=k_escolhido, random_state=42, n_init=10)
rotulos_finais = kmeans_final.fit_predict(X_padronizado)

# Crie df_resultados sem modificar as variáveis de entrada.
