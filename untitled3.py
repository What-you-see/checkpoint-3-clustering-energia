"""A padronização com o StandardScaler é essencial porque as variáveis possuem escalas e unidades de medida completamente diferentes (kWh em centenas/milhares, kW em unidades menores e percentuais de 0 a 100). Sem a padronização, variáveis com maiores amplitudes numéricas (como o consumo em kWh) dominariam o cálculo das distâncias euclidianas do algoritmo K-Means, tornando as outras variáveis irrelevantes. O StandardScaler coloca todas na mesma ordem de grandeza (média 0 e desvio padrão 1)."""

# Teste k de 1 a 8 com KMeans.
inercias = []
k_valores = range(1, 9)

for k in k_valores:
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X_padronizado)
    inercias.append(kmeans.inertia_)

# Armazene as inércias em distorcoes (conforme pedido pelo enunciado)
